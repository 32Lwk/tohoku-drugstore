def region_dir(region_id: str) -> str:
    return f"prefectures/09_北海道/data/regions/{region_id}"


def belongs_to_region(address: str, region_id: str) -> bool:
    if PREFECTURE not in (address or ""):
        return False
    cfg = REGIONS[region_id]
    return any(muni in address for muni in cfg["municipalities"])


def filter_stores_for_region(stores: list[dict], region_id: str) -> list[dict]:
    return [s for s in stores if belongs_to_region(s.get("address", ""), region_id)]


def all_region_ids() -> list[str]:
    return list(REGIONS.keys())
